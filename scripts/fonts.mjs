// Every word on screen is fixed in the source, so the fonts only need the characters this text uses.
// Fontsource ships ~95 unicode-range slices per Korean weight (~250 KB of render-blocking CSS, ~900 KB
// of font files over a visit). This keeps only the slices that contain used characters, narrows each
// unicode-range to those characters, and lists the slices for scripts/subset_fonts.py, which cuts each
// file down to the same characters into src/fonts/.
//
//   npm run fonts          regenerate CSS + font files (needs Python with fonttools[woff])
//   node scripts/fonts.mjs --check   fail if the committed fonts no longer cover the text (used by build)
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'

const root = new URL('../', import.meta.url)
const read = p => readFileSync(new URL(p, root), 'utf8')
const check = process.argv.includes('--check')

// Every character the app can render: source text, data labels, the page shell.
const sources = ['index.html', 'src/data/semantic.json', 'src/data/sets.json', ...readdirSync(new URL('src/', root)).filter(f => /\.(tsx|ts)$/.test(f)).map(f => `src/${f}`)]
const used = new Set([...sources.map(read).join('')].map(c => c.codePointAt(0)).filter(c => c >= 0x20)) // no control chars (line endings vary by checkout)
for (let c = 0x20; c < 0x7f; c++) used.add(c) // all printable ASCII, so nothing Latin ever falls back

const FACES = [
  ['ibm-plex-sans-kr', [300, 400, 500]],
  ['ibm-plex-mono', [300, 400]],
]

// The used characters a slice covers, as a (much shorter) unicode-range.
const narrow = range => {
  const spans = range.split(',').map(p => p.trim().replace(/^U\+/i, '').split('-').map(h => parseInt(h, 16)))
  const hit = [...used].filter(c => spans.some(([a, b]) => c >= a && c <= (b ?? a))).sort((x, y) => x - y)
  const out = []
  for (const c of hit) {
    const last = out[out.length - 1]
    if (last && c === last[1] + 1) last[1] = c; else out.push([c, c])
  }
  return out.map(([a, b]) => 'U+' + a.toString(16) + (b > a ? '-' + b.toString(16) : '')).join(',')
}

// One file per face and weight: the used slices of that weight, cut to the used characters and merged.
let css = '/* Generated by scripts/fonts.mjs. Do not edit; run npm run fonts after changing any on-screen text. */\n'
const jobs = []
let total = 0
for (const [pkg, weights] of FACES) {
  for (const w of weights) {
    const blocks = read(`node_modules/@fontsource/${pkg}/${w}.css`).match(/@font-face\s*{[^}]*}/g)
    total += blocks.length
    const srcs = [], ranges = []
    for (const block of blocks) {
      const mine = narrow(block.match(/unicode-range:\s*([^;]+);/)[1])
      if (!mine) continue
      srcs.push(`node_modules/@fontsource/${pkg}/files/${block.match(/files\/([^)]+\.woff2)/)[1]}`)
      ranges.push(mine)
    }
    const file = `${pkg}-${w}.woff2`, range = ranges.join(',')
    jobs.push({ srcs, out: `src/fonts/${file}`, range })
    css += blocks[0]
      .replace(/src:[^;]+;/, `src: url(./fonts/${file}) format('woff2');`)
      .replace(/unicode-range:\s*[^;]+;/, `unicode-range: ${range};`)
      .replace(/\/\*[^*]*\*\/\s*/g, '') + '\n'
  }
}

const cssPath = new URL('src/fonts.generated.css', root)
if (check) {
  const stale = !existsSync(cssPath) || readFileSync(cssPath, 'utf8').replace(/\r\n/g, '\n') !== css // ignore checkout line endings
  const missing = jobs.filter(j => !existsSync(new URL(j.out, root))).map(j => j.out)
  if (stale || missing.length) {
    console.error(`fonts: out of date with the on-screen text${missing.length ? ` (missing ${missing.length} files)` : ''}. Run: npm run fonts`)
    process.exit(1)
  }
  console.log(`fonts: up to date (${jobs.length} files)`)
} else {
  writeFileSync(cssPath, css)
  writeFileSync(new URL('scripts/.fonts-jobs.json', root), JSON.stringify(jobs))
  console.log(`fonts: ${jobs.reduce((n, j) => n + j.srcs.length, 0)} of ${total} slices in use; subsetting into ${jobs.length} files`)
}
